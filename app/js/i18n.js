KB.lang = 'en';

KB.t = function (key, params) {
  const table = KB.strings[KB.lang] || KB.strings.en;
  let s = key in table ? table[key] : KB.strings.en[key] || key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? params[k] : ''));
  return s;
};
